import java.util.Scanner;

public class For {
    void main() {
        Scanner sc = new Scanner(System.in);

        int n1 = 0;
        for (int i = 1; i <= 10; i++) {
            n1 = n1 + i;
        }
        System.out.println("La sumatoria de los números del 1 al 10 es igual a " + n1);

        System.out.println("----------------------------------------------------------------------");




    }
}
